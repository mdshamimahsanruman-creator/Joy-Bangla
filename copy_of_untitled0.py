def is_chain_valid(chain):
    for i in range(1, len(chain)):
        current = chain[i]
        previous = chain[i - 1]

        if current["previous_hash"] != previous["hash"]:
            return False

        if current["hash"] != joy_bangla.hash_block(
            {k: v for k, v in current.items() if k != "hash"}
        ):
            return False

    return True


